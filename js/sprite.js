const FRAMES = { idle: [IDLE], run: [IDLE, RUN1, RUN2], jump: [JUMP], hurt: [HURT] };

/**
 * Draw Mansfield onto a 2D context.
 * @param {CanvasRenderingContext2D} g
 * @param {number} x top-left x
 * @param {number} y top-left y
 * @param {number} size pixel-art rendered size (square)
 * @param {string} state idle|run|jump|hurt
 * @param {number} frameTick monotonically increasing tick for animation
 * @param {object} opts { flip:boolean, alpha:number, tint:string }
 */
export function drawMansfield(g, x, y, size, state, frameTick, opts = {}) {
  const frames = FRAMES[state] || FRAMES.idle;
  const grid = frames[Math.floor(frameTick / 6) % frames.length];
  const px = size / 16;
  g.save();
  if (opts.alpha != null) g.globalAlpha = opts.alpha;
  if (opts.flip) { g.translate(x + size, y); g.scale(-1, 1); x = 0; y = 0; }
  for (let r = 0; r < 16; r++) {
    const row = grid[r];
    for (let c = 0; c < 16; c++) {
      const v = row[c];
      if (!v) continue;
      g.fillStyle = opts.tint || PALETTE[v];
      // +0.5 overdraw kills seams between pixels
      g.fillRect(x + c * px, y + r * px, px + 0.5, px + 0.5);
    }
  }
  g.restore();
}

export const MANSFIELD_PALETTE = PALETTE;
